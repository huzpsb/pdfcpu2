function detectLang() {
    const saved = localStorage.getItem("pdfcpu2.webui.prefs");
    if (saved) {
        try {
            const p = JSON.parse(saved);
            if (p.lang === "en" || p.lang === "zh") return p.lang;
        } catch (_) {
        }
    }
    return (navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
}
