/* pdfcpu2 webui worker: loads app.wasm and exposes the engine via RPC. */
'use strict';

importScripts('wasm_exec.js');

let api = null;

function collectTransfers(v, out) {
    if (v instanceof Uint8Array) {
        if (v.buffer && !v.buffer.detached) out.push(v.buffer);
    } else if (Array.isArray(v)) {
        for (const x of v) collectTransfers(x, out);
    } else if (v && typeof v === 'object') {
        for (const k of Object.keys(v)) collectTransfers(v[k], out);
    }
}

async function boot() {
    try {
        if (typeof self.Go !== 'function') throw new Error('wasm_exec.js did not define Go');

        // Cache busting: version.txt is generated by the deploy workflow.
        let ver = '';
        try {
            const r = await fetch('version.txt', {cache: 'no-store'});
            if (r.ok) ver = (await r.text()).trim();
            else console.warn('[webui] version.txt: HTTP ' + r.status + ' (continuing without cache buster)');
        } catch (err) {
            console.warn('[webui] version.txt: ' + (err && err.message || err) + ' (continuing without cache buster)');
        }
        const url = 'app.wasm' + (ver ? '?v=' + encodeURIComponent(ver) : '');

        const go = new Go();
        let instance;
        try {
            const res = await WebAssembly.instantiateStreaming(fetch(url), go.importObject);
            instance = res.instance;
        } catch (e) {
            // Fallback for servers without the application/wasm MIME type.
            const buf = await (await fetch(url)).arrayBuffer();
            const res = await WebAssembly.instantiate(buf, go.importObject);
            instance = res.instance;
        }

        // The Go program parks in select{} for its whole life, so the promise
        // returned by go.run() never resolves. Do NOT await it — start it and
        // poll until the bridge has installed itself on the global object.
        go.run(instance).then(
            () => self.postMessage({type: 'error', error: 'engine exited unexpectedly'}),
            (err) => self.postMessage({type: 'error', error: String(err && err.message || err)}),
        );

        const deadline = Date.now() + 120000;
        while (!(self.pdfcpu2 && self.pdfcpu2.version)) {
            if (Date.now() > deadline) throw new Error('engine did not initialize in time');
            await new Promise((r) => setTimeout(r, 50));
        }
        api = self.pdfcpu2;
        let version = '';
        try {
            version = api.version().version;
        } catch (err) {
            console.warn('[webui] api.version():', err && err.message || err);
        }
        self.postMessage({type: 'ready', version});
    } catch (err) {
        self.postMessage({type: 'error', error: String(err && err.message || err)});
    }
}

self.onmessage = async (ev) => {
    const msg = ev.data || {};
    const {id, fn, args} = msg;
    if (!id || !fn) return;

    if (!api) {
        self.postMessage({type: 'rpc', id, ok: false, error: 'engine not ready yet'});
        return;
    }
    const f = api[fn];
    if (typeof f !== 'function') {
        self.postMessage({type: 'rpc', id, ok: false, error: 'unknown engine function: ' + fn});
        return;
    }
    try {
        const res = f.apply(null, args || []);
        const payload = {type: 'rpc', id, ok: true, res};
        const transfers = [];
        collectTransfers(res, transfers);
        self.postMessage(payload, transfers);
    } catch (err) {
        self.postMessage({type: 'rpc', id, ok: false, error: String(err && err.message || err)});
    }
};

boot();
